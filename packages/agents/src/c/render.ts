import { renderAnswer as renderAnswerB, renderReasoning as renderReasoningB, traceLines as traceLinesB } from '../b/output/render';
import type { CaseResultC, ReviewIssue, Round } from './types';

const list = (xs: string[], empty = '- None.') => (xs.length ? xs.map((x) => `- ${x}`).join('\n') : empty);
const refs = (xs: string[]) => (xs.length ? ` [${xs.join(', ')}]` : '');
const issueLine = (i: ReviewIssue) => `**${i.id}** ${i.severity} · ${i.tag}: ${i.claim}${refs(i.refs)}. Suggested fix: ${i.suggestion}`;

function roundBlock(r: Round): string[] {
  const out = [`### Round ${r.n}${r.model ? ` · reviewer ${r.model}` : ''}`, ''];
  if (r.checkIssues.length) out.push('**Automatic checks (blocking)**', list(r.checkIssues.map(issueLine)), '');
  if (r.review) {
    out.push(`**Review: ${r.review.verdict}**`, list(r.review.issues.map(issueLine), '- No issues raised.'));
    if (r.review.escalationReason) out.push(`- Escalation reason: ${r.review.escalationReason}`);
    out.push('');
  } else if (r.model) out.push('**Review:** not available (the reviewer call failed; see failures).', '');
  if (r.responses.length) out.push('**Agent’s answers**', list(r.responses.map((x) => `**${x.issueId}** ${x.verdict}: ${x.evidence}${refs(x.refs)}`)), '');
  if (r.revision) out.push(`**Revised plan:** \`${r.revision.domainAction ?? r.revision.action}\` → ${r.revision.recipient || '—'}: ${r.revision.actionLabel}`, '');
  return out;
}

function dialogue(r: CaseResultC): string {
  const out = ['## 5. Checks and review dialogue', ''];
  out.push(`Models: read ${r.models.read} · decide ${r.models.decide} · review ${r.models.critic}`, '');
  out.push('**Rule checks on the final candidate**', list(r.hardIssues.map((i) => `${i.severity} [${i.rule}] ${i.detail}`), '- All passed.'), '');
  if (!r.rounds.length) out.push('No review ran.', '');
  for (const round of r.rounds) out.push(...roundBlock(round));
  if (r.disputed.length) {
    out.push('**Still disputed after the last round** (the agent rejected these with evidence; the reviewer kept them):');
    out.push(list(r.disputed.map((d) => `${d.issue.id}: reviewer: ${d.issue.claim}${refs(d.issue.refs)} · agent: ${d.response.evidence}${refs(d.response.refs)}`)), '');
  }
  out.push(`Revised after review: ${r.revised ? 'yes' : 'no'}`, '');
  return out.join('\n');
}

export const renderAnswer = (r: CaseResultC) => renderAnswerB(r).replace('Generated by agent-b', 'Generated by agent-c');

export function renderReasoning(r: CaseResultC): string {
  const b = renderReasoningB(r);
  const start = b.indexOf('## 5. Checks and review');
  const end = b.indexOf('## 6. Decision');
  if (start < 0 || end < 0) return `${b}\n${dialogue(r)}`;
  return `${b.slice(0, start)}${dialogue(r)}\n${b.slice(end)}`;
}

export function traceLines(r: CaseResultC): string {
  return traceLinesB(r) + JSON.stringify({ stage: 'dialogue', models: r.models, rounds: r.rounds, disputed: r.disputed }) + '\n';
}
